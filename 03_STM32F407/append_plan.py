    f.write('\n\n## 六、未来的进阶计划：500Hz 工业级高清波形采样\n\n')
    f.write('既然我们在第五步中，通过分离“温度/距离”和“电容”彻底释放了单片机的 CPU 算力，现在的系统资源其实处于一种极其过剩的状态。针对飞沫监测场景（飞沫掠过传感器可能仅需 10~20 毫秒），100Hz（10毫秒1个点）的采样率略显不足，可能会导致波形呈现尖锐的三角形，丢失平滑的细节。\n\n')
    f.write('为了获得能在科研或高级算法中使用的“高清模拟波形”，我们可以将**电容采样率提升至 500Hz（2毫秒/次）**。这是一个完美的甜点区：既能捕捉飞沫瞬态波形，又不会让 I2C 接口过度占用 CPU。\n\n')
    f.write('**未来升级 500Hz 需要联动的三个代码修改点：**\n\n')
    f.write('1. **TIM2 定时器频率（采样提速）**：\n')
    f.write('   - **当前**：100Hz（每 10ms 采一次电容）。\n')
    f.write('   - **目标**：500Hz（每 2ms 采一次电容）。\n')
    f.write('   - **逻辑**：修改 `TIM2_Int_Init()` 的分频系数和重装载值，让定时器中断跑得更快。\n\n')
    f.write('2. **FIFO 内存队列扩容（防溢出重构）**：\n')
    f.write('   - **当前**：256 深度。在 100Hz 下能抗 2.56 秒的 WiFi 断网。\n')
    f.write('   - **目标**：2048 深度。\n')
    f.write('   - **逻辑**：由于采样率翻了 5 倍，同样的 2.5 秒 WiFi 断网物理卡顿，会瞬间产生 1250 个数据包。我们必须利用 STM32F407 的庞大内存，将 `FIFO_SIZE` 改为 `2048`，保证 500Hz 狂暴采样下的数据绝对安全无损。\n\n')
    f.write('3. **TCP 打包发车阈值（维持 20FPS 视觉流畅度）**：\n')
    f.write('   - **当前**：攒够 5 个包发一次（对应 50ms 间隔）。\n')
    f.write('   - **目标**：攒够 25 个包发一次（对应 50ms 间隔）。\n')
    f.write('   - **逻辑**：如果 500Hz 下依然 5 个包一发，那 WiFi 每 10 毫秒就要发一次，TCP 协议栈会瞬间被微小的包头淹没重新瘫痪。因此，我们将打包阈值提升至 `25`，单片机每次甩出 25 个包组成的大数据块，上位机依然能保持 50ms 刷新一次的完美 20FPS 视觉流畅度。\n\n')
    f.write('*（注：温度和距离传感器继续保持 1Hz 即 1000ms 刷新一次的极低频率，坚决不参与抢占 CPU。）*\n')
