    f.write('*   **不流畅（视觉掉帧感）：** 属于批量发送带来的**物理副作用（Visual Delay）**。\n')
    f.write('    由于我们改成了“攒够 10 个包（100毫秒）才发一次”，上位机也是每隔 100 毫秒才收到一次数据，这导致电脑屏幕上的波形是**一截一截（每截 10 个点）往外蹦的**，看起来像掉帧一样不连贯。\n')
