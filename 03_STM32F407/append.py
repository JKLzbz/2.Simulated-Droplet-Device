    f.write('之前的主循环跑得太快（100Hz），导致它每秒钟要通过软件 I2C 去读取 100 次温度和距离传感器。I2C 读取是一个非常慢的过程，包含大量的微秒级死循环延时（占用死区时间）。\n')
    f.write('这就导致：CPU 几乎把 90% 的时间都花在了“死等”温度传感器回传数据上。当 Wi-Fi 模块（ESP8266）需要单片机通过 SPI 喂数据时，CPU 根本抽不出空（**CPU 算力被 I2C 彻底榨干**）。一旦 Wi-Fi 遇到一点点网络波动，需要单片机配合处理，单片机却在忙着读温度，最终导致 Wi-Fi 缓冲区满，发生长达 1.4 秒的 STALL 假死。\n\n')
    f.write('**修复：传感器分频降速（彻底释放 CPU）**\n')
    f.write('我们在主循环里加了一把“分频锁”。让电容采集依然保持 100Hz 极速中断，但**温度和距离的读取频率被大幅降频到了 10Hz**（每 0.1 秒读一次，对于环境监测绰绰有余）。这瞬间释放了 CPU 90% 的算力，让主循环能全心全意伺候 Wi-Fi 发送，彻底消灭了因为 CPU 阻塞导致的规律性卡顿。\n\n')
    f.write('### 2. 为什么“10 个包打包发送”能缓解 TCP 拥塞？\n')
    f.write('想象一下你开了一家快递公司：\n')
    f.write('如果你每秒钟要寄 100 封小信件（每个数据包只有 13 字节），你需要让快递员跑 100 趟，填写 100 张复杂的快递单（TCP 包头、IP 包头、MAC 包头）。这种**“高频率、碎包发送”**会导致巨大的协议开销，ESP8266 的 TCP 协议栈会瞬间被成堆的快递单淹没，引发严重的网络拥塞。\n')
    f.write('**修复：批量发送（批处理）**\n')
    f.write('我们建立了一个 **FIFO 内存缓冲队列**。让中断只管往内存里扔数据，主循环去检查：**只有当内存里攒够了 10 个包（130 字节）时，才打包成一个大的 TCP 数据段，一次性发给上位机。**\n')
    f.write('这样一来，快递员每秒只需要跑 10 趟。这极大提高了“有效载荷比”，瞬间化解了 Wi-Fi 模块的网络堵塞压力。\n\n')
