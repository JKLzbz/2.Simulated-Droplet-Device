    f.write('\n\n---\n\n')
    f.write('## 单片机里只有 TIM 和 USART 两种中断吗？\n\n')
    f.write('**绝对不是！**\n')
    f.write('单片机（以 STM32 为例）拥有一个极其庞大且复杂的“危机响应中心”叫 **NVIC（嵌套向量中断控制器）**，它支持几十上百种不同的中断源。除了 TIM 和 USART，还有很多极为常用的中断：\n\n')
    f.write('1.  **EXTI 中断 (外部中断)**：\n')
    f.write('    *   **比方**：按门铃。\n')
    f.write('    *   **场景**：比如你板子上有一个物理按键。你不需要让总裁在主循环里每秒去问一百次“按键按下了吗？”，你只需要把按键引脚配置为下降沿 EXTI 中断。平时总裁根本不管按键，但只要你手一按，引脚电平一变，立马触发 EXTI 中断。很多极低功耗的智能门锁就是靠这个机制唤醒休眠的。\n')
    f.write('2.  **DMA 中断 (直接内存访问完成中断)**：\n')
    f.write('    *   **比方**：外包团队完成汇报。\n')
    f.write('    *   **场景**：当单片机要往 SD 卡写一张几百 KB 的照片时，如果让 CPU 自己去搬砖，它就瘫痪了。CPU 会叫 DMA（专门搬砖的独立硬件）去搬。DMA 搬完几十万个字节后，会触发一个 DMA 传输完成中断，告诉 CPU：“老板，活干完了！”\n')
    f.write('3.  **ADC 中断 (模数转换中断)**：\n')
    f.write('    *   **比方**：体检报告出炉。\n')
    f.write('    *   **场景**：当你测量电池电压时，ADC 硬件转换电压可能需要几十微秒。转换完成后，会触发 ADC 中断，通知 CPU 来取走电压数值。\n')
    f.write('4.  **I2C / SPI 通信中断**：\n')
    f.write('    *   类似于串口，当这些硬件总线上收发完一个字节时，也可以触发中断来通知 CPU，而不需要 CPU 去死等。\n\n')
    f.write('### 总结\n')
    f.write('**主循环是用来干“又脏又累又不着急”的活的（比如打包网络协议、处理 UI、发串口、读慢速传感器）。**\n')
    f.write('**中断是用来处理“极度对时间敏感、一眨眼就会错过”的突发事件的（比如百赫兹级别的采样、捕获瞬间的按键、接收稍纵即逝的串口数据）。**\n')
