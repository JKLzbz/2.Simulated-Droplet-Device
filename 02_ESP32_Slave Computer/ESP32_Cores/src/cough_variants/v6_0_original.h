// ==========================================
// V1.取消预按下，基于铁芯机械延迟补偿的时序
// 总周期: ~3100ms
// 黄金爆破点: T = 3000ms（铁芯跑完 6.87ms 机械延迟后恰好全开）
//
// 设计原理：
//   - T=3000ms 为绝对物理爆破点：浓雾 + 高压气流在文丘里喷嘴完美交汇
//   - 雾化采用 LX8201_PB3_PIN (GPIO25) 直接电平控制，无防抖延迟
//   - 电磁阀提前 6.873ms 发令，精确补偿铁芯机械延迟
//   - 停泵节点与阀门全开同步，最大化瞬态冲击力（伯努利卷吸效应）
//   - 激光与阀门联动：开阀时亮，关阀时灭，精确照射喷射窗口
// ==========================================
void triggerPerfectCough(int pumpSpeed) {
  Serial.println("\n--- V1. 咳嗽序列启动 (爆破点 T=3000ms) ---");

  // ==========================================
  // 阶段 0：前期蓄压 (0 ~ 2800ms)
  // 阀门关闭状态下气泵运行，构建高压气动电容
  // ==========================================
  Serial.println("[T=0] 气泵开始蓄压...");
  ledcWrite(PUMP_CHANNEL, pumpSpeed);
  delay(2800);

  // ==========================================
  // 阶段 1：蓄雾供弹 (2800 ~ 2993ms)
  // ESP32 纳秒级翻转 GPIO，LX8201 起振
  // 2800~2815ms：缓启动，暂未出雾
  // 2815~3000ms：疯狂产雾 185ms，浓雾填满文丘里喉管副腔
  // ==========================================
  Serial.println("[T=2800] 开启雾化（LX8201 PB3 拉高）...");
  digitalWrite(LX8201_PB3_PIN, HIGH); // 电平直接触发，无机械防抖

  // 等待 193ms（15ms缓启动 + 178ms浓雾填满枪膛）
  // 设计为 193ms 是因为后续留 7ms 给电磁阀提前量（193 + 7 = 200ms）
  delay(193);
  delayMicroseconds(127); // 补上丢失的 127 微秒，此时 T = 2993.127 ms

  // ==========================================
  // 阶段 2：电磁阀发令 & 黄金爆破 (2993.127 ~ 3050ms)
  // 提前 6.873ms 发出电磁阀开启信号，精确补偿铁芯机械延迟
  // 铁芯在管中飞行 6873 微秒后，绝对时间恰好到达 T = 3000ms
  // ==========================================
  Serial.println("[T=2993.127] 电磁阀发令！铁芯起飞...");
  digitalWrite(VALVE_PIN, HIGH);

  // 精确补偿 6.873ms 铁芯绝对机械延迟
  // ESP32 在此原地等待，物理世界与代码在 T=3000ms 精确会师
  delayMicroseconds(6873);

  // T = 2993.127 + 6.873 = 3000.000 ms —— 黄金爆破点！
  // 铁芯刚好撞顶，阀门绝对全开，停泵交由储气室瞬态释放
  Serial.println("[T=3000] 黄金爆破点！阀门全开，停泵，咳嗽瞬态爆发！");
  ledcWrite(PUMP_CHANNEL, 0);
  ledcWrite(LASER_CHANNEL, 1023); // 激光随阀门全开同步点亮，照射喷射窗口

  // 维持咳嗽爆发期 50ms（高压气流裹挟浓雾完美喷出）
  delay(50);

  // ==========================================
  // 阶段 3：断雾与清风扫膛 (3050 ~ 3100ms)
  // 断水，利用管道残余气压吹走挂壁雾气
  // ==========================================
  Serial.println("[T=3050] 关闭雾化（断水），清风扫膛开始...");
  digitalWrite(LX8201_PB3_PIN, LOW); // 断水

  // 电磁阀保持开启，残余气压吹空炮 50ms，确保无积水挂珠
  delay(50);

  // ==========================================
  // 阶段 4：彻底闭锁 (T=3100ms)
  // ==========================================
  Serial.println("[T=3100] 关闭电磁阀，咳嗽周期安全结束。");
  digitalWrite(VALVE_PIN, LOW);
  ledcWrite(LASER_CHANNEL, 0);    // 阀门关闭，激光同步熄灭
  Serial.println("--- V1. 咳嗽周期结束，系统安全闭锁 ---\n");
}
